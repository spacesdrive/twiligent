interface IconSet {
  icons: Record<string, { body: string }>;
  aliases?: Record<string, { parent: string }>;
}

const here = dirname(fileURLToPath(import.meta.url));
const setPath = join(here, '..', '..', 'node_modules', '@iconify-json', 'solar', 'icons.json');
const set = JSON.parse(readFileSync(setPath, 'utf8')) as IconSet;

function body(name: string): string {
  const icon = set.icons[name] ?? set.icons[set.aliases?.[name]?.parent ?? ''];
  if (!icon) throw new Error(`Solar has no icon named ${name}`);
  return icon.body;
}

const lines = Object.entries(ICONS).map(
  ([exportName, solarName]) =>
    `export const ${exportName} = /* @__PURE__ */ solar(${JSON.stringify(body(solarName))});`,
);

const file = `// generated by build/genIcons.ts; edit the list there and run \`npm run icons --workspace site\`
// icons from Solar by 480 Design, CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/), credited in THIRD_PARTY_NOTICES.md
import type { SVGProps } from 'react';

export type IconProps = Omit<SVGProps<SVGSVGElement>, 'dangerouslySetInnerHTML' | 'children'>;
export type Icon = (props: IconProps) => React.JSX.Element;

// each icon draws in currentColor at 1em, so it takes its colour and size from the text beside it
function solar(markup: string): Icon {
  return function SolarIcon(props: IconProps) {
    return <svg viewBox="0 0 24 24" width="1em" height="1em" aria-hidden="true" focusable="false" {...props} dangerouslySetInnerHTML={{ __html: markup }} />;
  };
}

${lines.join('\n')}
`;

writeFileSync(join(here, '..', 'src', 'components', 'icons.tsx'), file);
console.log(`wrote ${Object.keys(ICONS).length} icons`);
